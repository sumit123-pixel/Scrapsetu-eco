  const SUPPORTED = ['en', 'hi', 'mr'];
  let currentLang = localStorage.getItem('scrapsetu_lang') || 'en';
  if (!SUPPORTED.includes(currentLang)) currentLang = 'en';

  function t(key) {
    const dict = TRANSLATIONS[currentLang] || {};
    if (dict[key] != null) return dict[key];
    if (TRANSLATIONS.en[key] != null) return TRANSLATIONS.en[key];
    return key;
  }

  function apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    document.documentElement.lang = currentLang;
    document.querySelectorAll('.lang-select').forEach(sel => { sel.value = currentLang; });
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) return;
    currentLang = lang;
    localStorage.setItem('scrapsetu_lang', lang);
    apply();
    window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
  }

  window.t = t;
  window.setLang = setLang;
  window.getLang = () => currentLang;
  window.SUPPORTED_LANGS = SUPPORTED;

  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.lang-select').forEach(sel => {
      sel.value = currentLang;
      sel.addEventListener('change', e => setLang(e.target.value));
    });
    apply();
  });
